# Default ASS style for karaoke effect.
# Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, 
# Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, 
# BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
#
# - PrimaryColour: The color the text becomes *after* the karaoke sweep (highlighted color).
# - SecondaryColour: The color the text is *before* the karaoke sweep (base color).
# - Alignment: 2 is bottom center. 5 is middle center. 8 is top center.
#   (Numpad layout: 1-bottom-left, 2-bottom-center, 3-bottom-right, 4-mid-left, ..., 9-top-right)
# - MarginV: 80 = vertical margin from bottom (pixels from bottom edge)
# - MarginL/MarginR: 10 = left/right margins (pixels from edges)
# Encoding: 1 = System default, 0 = UTF-8. Let's use 0 for wider compatibility.
#
# POSITION EXAMPLES:
# Bottom quarter (current): Alignment=2, MarginV=80
# Middle center: Alignment=5, MarginV=0  
# Top quarter: Alignment=8, MarginV=80
# Bottom left: Alignment=1, MarginV=80
